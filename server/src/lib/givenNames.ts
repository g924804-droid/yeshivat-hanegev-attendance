// "שי" ו"שמחה" הם גם שמות משפחה — לא נכריע לפיהם
GIVEN_NAMES.delete('שי');
export const isGivenName = (v: string) => GIVEN_NAMES.has(v) || (v.includes(' ') && v.split(' ').every((w) => GIVEN_NAMES.has(w)));
